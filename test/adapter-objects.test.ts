import assert from "node:assert/strict";
import { test } from "node:test";
import { DatabricksAdapter } from "../src/adapters/databricks.js";
import { MysqlAdapter } from "../src/adapters/mysql.js";
import { OracleAdapter } from "../src/adapters/oracle.js";
import { PostgresAdapter } from "../src/adapters/postgres.js";
import { SnowflakeAdapter } from "../src/adapters/snowflake.js";
import { SqliteAdapter } from "../src/adapters/sqlite.js";
import type { ColumnInfo, ForeignKeyInfo, TableInfo } from "../src/types.js";

const col = (name: string, type: ColumnInfo["type"], o: Partial<ColumnInfo> = {}): ColumnInfo => ({ name, nativeType: type, type, nullable: true, ...o });

const table: TableInfo = {
  name: "customers",
  primaryKey: ["id"],
  columns: [
    col("id", "bigint", { nullable: false, identity: { start: "42" } }),
    col("status", "string", { length: 10, nullable: false, default: { kind: "literal", value: "it's new" } }),
    col("active", "boolean", { default: { kind: "literal", value: true } }),
    col("score", "integer", { default: { kind: "literal", value: 5 } }),
    col("created", "timestamptz", { default: { kind: "now" } }),
    col("born", "date", { default: { kind: "today" } }),
  ],
};
const fk: ForeignKeyInfo = { name: "fk_o_c", columns: ["customer_id"], refTable: "customers", refColumns: ["id"], onDelete: "CASCADE", onUpdate: "SET NULL" };

test("postgres: identity continues from the start value, defaults are quoted safely", () => {
  const a = new PostgresAdapter({ type: "postgres" });
  const ddl = a.ddlFor(table, { pkName: "pk_customers" });
  assert.match(ddl, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY \(START WITH 42\) NOT NULL/);
  assert.match(ddl, /"status" VARCHAR\(10\) DEFAULT 'it''s new' NOT NULL/);
  assert.match(ddl, /"active" BOOLEAN DEFAULT TRUE/);
  assert.match(ddl, /"created" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP/);
  assert.match(ddl, /"born" DATE DEFAULT CURRENT_DATE/);
  assert.equal(a.foreignKeySql("orders", fk), 'ALTER TABLE "public"."orders" ADD CONSTRAINT "fk_o_c" FOREIGN KEY ("customer_id") REFERENCES "public"."customers" ("id") ON DELETE CASCADE ON UPDATE SET NULL');
  assert.throws(() => a.ddlFor({ ...table, columns: [col("id", "bigint", { identity: { start: "1; DROP TABLE x" } })] }), /Invalid identity start/);
});

test("mysql: AUTO_INCREMENT, precision-matched CURRENT_TIMESTAMP, expression date default, DROP FOREIGN KEY", async () => {
  const a = new MysqlAdapter({ type: "mysql" });
  const ddl = a.ddlFor(table, { pkName: "pk" });
  assert.match(ddl, /`id` BIGINT NOT NULL AUTO_INCREMENT/);
  assert.match(ddl, /`created` DATETIME\(6\) DEFAULT CURRENT_TIMESTAMP\(6\)/);
  assert.match(ddl, /`born` DATE DEFAULT \(CURRENT_DATE\)/);
  assert.match(ddl, /`active` TINYINT\(1\) DEFAULT 1/);
  const sqls: string[] = [];
  (a as any).exec = async (s: string) => void sqls.push(s);
  await a.dropForeignKey("orders", "fk_o_c");
  await a.createIndex("orders", { name: "ix", columns: ["a", "b"], unique: true });
  assert.deepEqual(sqls, ["ALTER TABLE `orders` DROP FOREIGN KEY `fk_o_c`", "CREATE UNIQUE INDEX `ix` ON `orders` (`a`, `b`)"]);
});

test("oracle: identity clause, no ON UPDATE, owner-qualified index names", async () => {
  const a = new OracleAdapter({ type: "oracle" });
  (a as any).owner = "APP";
  assert.match(a.ddlFor(table), /"id" NUMBER\(19,0\) GENERATED BY DEFAULT AS IDENTITY \(START WITH 42\) NOT NULL/);
  assert.match(a.ddlFor(table), /"active" NUMBER\(1,0\) DEFAULT 1/);
  assert.match(a.foreignKeySql("orders", fk), /ON DELETE CASCADE$/);
  const sqls: string[] = [];
  (a as any).exec = async (s: string) => void sqls.push(s);
  await a.createIndex("T", { name: "IX", columns: ["A"], unique: false });
  assert.equal(sqls[0], 'CREATE INDEX "APP"."IX" ON "APP"."T" ("A")');
});

test("snowflake: AUTOINCREMENT with start, function-style current_timestamp; no indexes or foreign keys", () => {
  const a = new SnowflakeAdapter({ type: "snowflake" });
  const ddl = a.ddlFor(table);
  assert.match(ddl, /"id" BIGINT AUTOINCREMENT START 42 INCREMENT 1 NOT NULL/);
  assert.match(ddl, /"created" TIMESTAMP_TZ\(6\) DEFAULT CURRENT_TIMESTAMP\(\)/);
  assert.equal(a.supportsIndexes, false);
  assert.equal(a.foreignKeyMode, "none");
  assert.equal(new SnowflakeAdapter({ type: "snowflake", identity: false }).supportsIdentity, false);
});

test("snowflake: snapshot reads use Time Travel, and only when switched on", async () => {
  const off = new SnowflakeAdapter({ type: "snowflake" });
  assert.equal(await off.beginSnapshot(), false);
  const a = new SnowflakeAdapter({ type: "snowflake", snapshot: true });
  const sqls: string[] = [];
  (a as any).query = async (s: string) => {
    sqls.push(s);
    return [["2026-11-10 12:00:00.123 +0000"]];
  };
  assert.equal(await a.beginSnapshot(), true);
  await a.countRows("T");
  assert.match(sqls[1], /FROM "".""."T" AT\(TIMESTAMP => TO_TIMESTAMP_TZ\('2026-11-10 12:00:00.123 \+0000', /);
  await a.endSnapshot();
  await a.countRows("T");
  assert.doesNotMatch(sqls[2], /AT\(TIMESTAMP/);
});

test("databricks: identity is BIGINT; defaults are opt-in and enable the Delta feature; strings are injection-proof", async () => {
  const a = new DatabricksAdapter({ type: "databricks" });
  assert.match(a.ddlFor(table), /`id` BIGINT GENERATED BY DEFAULT AS IDENTITY \(START WITH 42 INCREMENT BY 1\) NOT NULL/);
  assert.doesNotMatch(a.ddlFor(table).replace("GENERATED BY DEFAULT", ""), /DEFAULT/); // column defaults are off unless asked for
  const d = new DatabricksAdapter({ type: "databricks", defaults: true });
  const ddl = d.ddlFor({ ...table, columns: [...table.columns, col("t", "string", { default: { kind: "literal", value: "café'; DROP" } })] });
  assert.match(ddl, /`status` STRING DEFAULT decode\(unhex\('[0-9a-f]+'\), 'UTF-8'\) NOT NULL/);
  assert.match(ddl, /USING DELTA TBLPROPERTIES \('delta\.feature\.allowColumnDefaults' = 'supported'\)/);
  assert.doesNotMatch(ddl, /DROP'/);
  const s = new DatabricksAdapter({ type: "databricks", snapshot: true });
  const sqls: string[] = [];
  (s as any).query = async (q: string) => (sqls.push(q), [["2026-11-10 12:00:00.123"]]);
  await s.beginSnapshot();
  await s.countRows("t");
  assert.match(sqls[1], /TIMESTAMP AS OF '2026-11-10 12:00:00.123'/);
});

test("sqlite: identity columns are exactly INTEGER (the rowid alias) and foreign keys are declared inline", () => {
  const a = new SqliteAdapter({ type: "sqlite", path: ":memory:" });
  const ddl = a.ddlFor(table, { pkName: "pk", foreignKeys: [{ ...fk, columns: ["id"], refTable: "other", refColumns: ["id"] }] });
  assert.match(ddl, /"id" INTEGER NOT NULL/);
  assert.match(ddl, /CONSTRAINT "fk_o_c" FOREIGN KEY \("id"\) REFERENCES "other" \("id"\) ON DELETE CASCADE ON UPDATE SET NULL/);
});

// ---- the row-handling half of describeExtras, fed with rows shaped like each catalog returns them

function stubQuery(a: any, answers: [RegExp, unknown[][]][]) {
  a.query = async (sql: string) => {
    const hit = answers.find(([re]) => re.test(sql));
    return hit ? hit[1] : [];
  };
}

test("mysql describeExtras: AUTO_INCREMENT, literal and expression defaults, indexes, foreign keys", async () => {
  const a = new MysqlAdapter({ type: "mysql" });
  stubQuery(a, [
    [/information_schema\.columns/, [
      ["id", null, "auto_increment", ""],
      ["status", "new", "", ""],
      ["active", "1", "", ""],
      ["created", "CURRENT_TIMESTAMP", "DEFAULT_GENERATED", ""],
      ["token", "(uuid())", "DEFAULT_GENERATED", ""],
      ["full", null, "STORED GENERATED", "concat(a,b)"],
    ]],
    [/information_schema\.statistics/, [
      ["ix_status", 1, "status", null, "BTREE"],
      ["ix_status", 1, "created", null, "BTREE"],
      ["ux_email", 0, "email", null, "BTREE"],
      ["ft_body", 1, "body", null, "FULLTEXT"],
      ["ix_prefix", 1, "name", 10, "BTREE"],
    ]],
    [/referential_constraints/, [["fk_c", "customer_id", "customers", "id", "CASCADE", "NO ACTION", "db"]]],
  ]);
  const x = await a.describeExtras("orders");
  assert.equal(x.identity, "id");
  assert.deepEqual(x.defaults, { status: { kind: "literal", value: "new" }, active: { kind: "literal", value: "1" }, created: { kind: "now" } });
  assert.deepEqual(x.indexes, [
    { name: "ix_status", columns: ["status", "created"], unique: false },
    { name: "ux_email", columns: ["email"], unique: true },
  ]);
  assert.deepEqual(x.foreignKeys, [{ name: "fk_c", columns: ["customer_id"], refTable: "customers", refColumns: ["id"], onUpdate: "CASCADE", onDelete: "NO ACTION" }]);
  assert.ok(x.notes.some((n) => /uuid/.test(n)));
  assert.ok(x.notes.some((n) => /FULLTEXT/.test(n)));
  assert.ok(x.notes.some((n) => /prefix/.test(n)));
  assert.ok(x.notes.some((n) => /generated column/.test(n)));
});

test("oracle describeExtras: identity, defaults, indexes (skipping function-based), foreign keys with delete rules", async () => {
  const a = new OracleAdapter({ type: "oracle" });
  (a as any).owner = "APP";
  stubQuery(a, [
    [/all_tab_columns/, [["STATUS", "'new' "], ["CREATED", "SYSDATE"], ["ID", '"APP"."ISEQ$$_12345".nextval'], ["X", "my_pkg.fn()"]]],
    [/all_tab_identity_cols/, [["ID"]]],
    [/all_indexes/, [
      ["IX_A", "NONUNIQUE", "NORMAL", "STATUS", 1],
      ["IX_A", "NONUNIQUE", "NORMAL", "CREATED", 2],
      ["UX_B", "UNIQUE", "NORMAL", "EMAIL", 1],
      ["IX_F", "NONUNIQUE", "FUNCTION-BASED NORMAL", "SYS_NC0001$", 1],
      ["SYS_IL0001", "UNIQUE", "LOB", "BODY", 1],
    ]],
    [/constraint_type = 'R'/, [["FK_C", "CUSTOMER_ID", "CUSTOMERS", "ID", "SET NULL", "APP"], ["FK_X", "OTHER_ID", "OTHERS", "ID", "NO ACTION", "OTHERAPP"]]],
  ]);
  const x = await a.describeExtras("ORDERS");
  assert.equal(x.identity, "ID");
  assert.deepEqual(x.defaults, { STATUS: { kind: "literal", value: "new" }, CREATED: { kind: "now" } });
  assert.deepEqual(x.indexes.map((i) => i.name), ["IX_A", "UX_B"]);
  assert.deepEqual(x.foreignKeys.map((f) => [f.name, f.onDelete]), [["FK_C", "SET NULL"]]);
  assert.ok(x.notes.some((n) => /function-based/.test(n)));
  assert.ok(x.notes.some((n) => /another schema/.test(n)));
  assert.ok(x.notes.some((n) => /my_pkg/.test(n)));
});

test("snowflake and databricks describeExtras read identity and defaults, and databricks tolerates catalogs without information_schema", async () => {
  const s = new SnowflakeAdapter({ type: "snowflake" });
  stubQuery(s, [[/information_schema\.columns/, [["ID", null, "YES"], ["STATUS", "'new'", "NO"], ["TS", "CURRENT_TIMESTAMP()", "NO"], ["SEQ", "MYSEQ.NEXTVAL", "NO"]]]]);
  const sx = await s.describeExtras("T");
  assert.equal(sx.identity, "ID");
  assert.deepEqual(sx.defaults, { STATUS: { kind: "literal", value: "new" }, TS: { kind: "now" } });
  assert.ok(sx.notes.some((n) => /NEXTVAL/.test(n)));

  const d = new DatabricksAdapter({ type: "databricks" });
  (d as any).query = async () => {
    throw new Error("no information_schema");
  };
  const dx = await d.describeExtras("t");
  assert.deepEqual(dx.defaults, {});
  assert.ok(dx.notes.some((n) => /no information_schema/.test(n)));
  assert.deepEqual(await d.listObjects(), []);
});
